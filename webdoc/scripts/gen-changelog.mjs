/**
 * Writes the changelog page, src/content/docs/reference/changelog.md, from the
 * repository's CHANGELOG.md. Runs before `astro dev` and `astro build`.
 *
 * This generator departs from the convention of every other one here: its
 * output is NOT committed and NOT covered by `gen:check`. CHANGELOG.md takes
 * release commits from other maintainers and from the release flow
 * ("changelog: 2.0.4 is dated [skip ci]"), and a committed copy would be stale
 * after each of them, failing the next docs run for a change nobody made to the
 * docs. So the page is written to a gitignored path at build time. The docs
 * workflow lists CHANGELOG.md among its paths, so a changelog commit redeploys
 * the site, except a commit marked `[skip ci]`, as the release flow's "is
 * dated" commits are: their text reaches the site with the next docs build.
 *
 * For the same reason nothing in CHANGELOG.md fails this script once its two
 * markers are found. An em dash, which the docs do not use, is written as a
 * spaced hyphen and reported, so a release note from elsewhere cannot break
 * the build of an unrelated docs change.
 *
 * Why the page exists: before 2.0.0 Queen MQ kept its data in PostgreSQL, and
 * the descriptions of it elsewhere on the web still say so. This page is the
 * dated, citable statement on the site itself that 2.0 replaced PostgreSQL.
 *
 * Scope: from the first `## ` heading down to the first 1.x heading, so the
 * 2.x releases and the undated "PHP client and Laravel supervisor" block. The
 * 1.x entries describe the PostgreSQL broker and stay on GitHub.
 *
 * The output is plain `.md`, not `.mdx`: release notes quote code such as
 * `{ toEnd: true }` and `<QUEEN_RAFT_DIR>`, which MDX would read as JSX.
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { REPO, WEBDOC } from "./lib/source.mjs";

const SOURCE = join(REPO, "CHANGELOG.md");
const OUT = join(WEBDOC, "src", "content", "docs", "reference", "changelog.md");
const SITE = "https://queenmq.com";

function die(message) {
  console.error(`gen-changelog: ${message}`);
  process.exit(1);
}

const lines = readFileSync(SOURCE, "utf8").split("\n");
const start = lines.findIndex((l) => /^## /.test(l));
const end = lines.findIndex((l) => /^## 1\./.test(l));
if (start === -1) die("CHANGELOG.md has no `## ` release heading.");
if (end === -1 || end <= start) die("CHANGELOG.md has no `## 1.` heading to stop at, below the first release.");

// check-prose would fail on an em dash in the generated file, which nobody
// edits. Write it as a spaced hyphen and point at the source line instead.
const range = lines.slice(start, end).map((line, i) => {
  if (!line.includes("—")) return line;
  console.warn(`gen-changelog: CHANGELOG.md:${start + i + 1} has an em dash; written as " - " on the site.`);
  return line.replace(/\s*—\s*/g, " - ");
});

// Absolute links to this site become site-relative: `nimbus/no-self-host-url`
// rejects the absolute form, and `nimbus/internal-link` then checks the path.
const body = range.join("\n").replaceAll(`](${SITE}/`, "](/").trimEnd();

const dates = [...body.matchAll(/^## .*?(\d{4}-\d{2}-\d{2})\s*$/gm)].map((m) => m[1]).sort();
const newest = dates.at(-1);
if (!newest) die("no `## ... YYYY-MM-DD` heading in the 2.x releases.");

const page = `---
# Generated by webdoc/scripts/gen-changelog.mjs from CHANGELOG.md at build time.
# Not committed: edit CHANGELOG.md.
title: "Queen MQ changelog: releases since 2.0"
description: "Every release since 2.0.0, which replaced PostgreSQL with a Raft log on local disk: the broker, the clients, the Laravel driver and the supervisor, newest first."
type: changelog
tier: use
generated: true
lastUpdated: ${newest}
sidebar:
  label: "Changelog"
  order: 11
---

Before 2.0.0 (2026-10-03), Queen MQ kept its data in PostgreSQL. 2.0 replaced that with its own
log, replicated with Raft, on each node's local disk, and a 2.0 node does not read a 1.x database.
This page lists every release since 2.0.0, newest first. The 1.x entries are in
[CHANGELOG.md on GitHub](https://github.com/queen-mq/queen/blob/master/CHANGELOG.md).

${body}
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, page);
console.log(`ok  changelog: ${dates.length} dated releases, newest ${newest}`);
